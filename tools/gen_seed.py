# ---- 规范化与去重 ----
STRIP = " \t\r\n" + "：:，,、·.。！!？?（）()《》“”‘’" + "'" + r"\-—–_/[]{}<>#;；"
# 同书异名（规范后）→ 已存在的规范名
ALIASES = {
    "一九八四": "1984",
    "女仆的故事": "使女的故事",
    "丛林": "屠场",
    "俄亥俄温斯堡": "小城畸人",
}
# 同书但需统一采用的书名
PREFERRED_TITLE = {
    "俄亥俄，温斯堡": "小城畸人",
}


def norm(title):
    t = title
    for ch in STRIP:
        t = t.replace(ch, "")
    return t.lower()


def go_quote(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    out = io.StringIO()
    out.write("// Code generated by tools/gen_seed.py; DO NOT EDIT BY HAND.\n")
    out.write("// 种子：26 个题材分类、11 个地区、完整馆藏（首次建库时写入）。\n\n")
    out.write("package store\n\n")
    out.write("// seedBook 描述一本待写入的种子图书。\n")
    out.write("type seedBook struct {\n")
    out.write("\tisbn, title, author, publisher, cat, region, loc string\n")
    out.write("\tqty int\n")
    out.write("}\n\n")

    out.write("// seedCategories 种子题材分类。\n")
    out.write("var seedCategories = []string{\n")
    for c in CATEGORIES:
        out.write("\t" + go_quote(c) + ",\n")
    out.write("}\n\n")
    out.write("// seedRegions 种子地区（顺序即展示顺序）。\n")
    out.write("var seedRegions = []string{\n")
    for r in REGIONS:
        out.write("\t" + go_quote(r) + ",\n")
    out.write("}\n\n")

    # 先放原 10 本 + 历次新增（权威，保留）
    rows = []
    for (isbn, title, author, pub, cat, region, loc, qty) in ORIGINALS:
        rows.append((isbn, title, author, pub, cat, region, loc, qty))
    cat_index = {c: i + 1 for i, c in enumerate(CATEGORIES)}
    per_cat_counter = {}
    seq = 0
    for (title, author, cat, region) in NEW:
        assert cat in cat_index, "未知题材分类: " + cat
        seq += 1
        per_cat_counter[cat] = per_cat_counter.get(cat, 0) + 1
        rows.append(("LMS-%04d" % seq, title, author, "", cat, region,
                     "N%02d-%03d" % (cat_index[cat], per_cat_counter[cat]), 3))

    # 合并地区书单：按规范书名去重
    seen = {}
    for r in rows:
        seen[norm(r[1])] = r[1]
    skipped = []
    for (region, title, author) in REGIONAL:
        key = norm(title)
        key = ALIASES.get(key, key)
        if key in seen:
            skipped.append((title, "duplicate of " + seen[key]))
            continue
        out_title = PREFERRED_TITLE.get(title, title)
        cat = genre_for(out_title, region)
        seq += 1
        per_cat_counter[cat] = per_cat_counter.get(cat, 0) + 1
        rec = ("LMS-%04d" % seq, out_title, author, "", cat, region,
               "N%02d-%03d" % (cat_index[cat], per_cat_counter[cat]), 3)
        rows.append(rec)
        seen[key] = out_title

    # 最终唯一性
    final_keys = [norm(r[1]) for r in rows]
    assert len(final_keys) == len(set(final_keys)), "仍存在重复: " + \
        str([k for k in final_keys if final_keys.count(k) > 1])

    out.write("// seedBooks 种子图书（原示例在前，其后为历次与地区馆藏）。\n")
    out.write("var seedBooks = []seedBook{\n")
    for (isbn, title, author, pub, cat, region, loc, qty) in rows:
        out.write(
            "\t{" + ", ".join([
                go_quote(isbn), go_quote(title), go_quote(author), go_quote(pub),
                go_quote(cat), go_quote(region), go_quote(loc), str(qty),
            ]) + "},\n"
        )
    out.write("}\n")

    target = r"C:\Users\Lenovo\Desktop\PJ\lms-modern\backend\internal\store\seed_catalog.go"
    with open(target, "wb") as f:
        f.write(out.getvalue().encode("utf-8"))

    print("categories", len(CATEGORIES), "regions", len(REGIONS))
    print("total books", len(rows))
    print("skipped from regional list", len(skipped))
    # 地区分布
    dist = {}
    for r in rows:
        dist[r[5]] = dist.get(r[5], 0) + 1
    for rg in REGIONS:
        print("  %-22s %d" % (rg, dist.get(rg, 0)))
    print("written", target)


